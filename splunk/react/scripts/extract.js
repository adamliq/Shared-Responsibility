/**
 * Extracts the dependency-free Cypher engine, example queries, graph layout and palette from the
 * standalone explorer (../../index.html) into an ES module, so the Splunk page and the static
 * explorer share one implementation. Run automatically by `npm run build`.
 */
const fs = require('fs');
const path = require('path');

const html = fs.readFileSync(path.join(__dirname, '../../../index.html'), 'utf8');
function slice(startMarker, endMarker) {
    const start = html.indexOf(startMarker);
    if (start < 0) throw new Error(`Marker not found: ${startMarker}`);
    const end = html.indexOf(endMarker, start);
    if (end < 0) throw new Error(`End marker not found after: ${startMarker}`);
    return html.slice(start, end + endMarker.length);
}
const parts = [
    slice('const GR_PALETTE=', ';'),
    slice('function grLayout(', '\n}\n'),
    slice('const CY=(()=>{', '\n})();'),
    slice('const CY_EXAMPLES=[', '\n];'),
];
// Organisation-profile rules (validation, overlay, workbook import and reports), so the Splunk app
// applies an organisation's own information exactly as the standalone explorer does.
const profile = [
    slice('function roleContains(', '\n'),
    slice('function rasciValid(', '\n'),
    slice('const PROFILE_KEY=', '\n// Applies the profile').replace(/\n\/\/ Applies the profile$/, ''),
    slice('function parseCSV(', '\nfunction toCSV(').replace(/\nfunction toCSV\($/, ''),
    slice('function toCSV(', '\n'),
    slice('function workbookRows(', '\n'),
    slice('// Converts workbook rows', '\nconst slug='),
].join('\n').replace(/\nconst slug=$/, '');
const out = `/* eslint-disable */
// Generated by scripts/extract.js from index.html. Do not edit; edit index.html instead.
${parts.join('\n')}
let controls = [];
${profile}
/** Sets the baseline, the active profile and the effective controls the profile functions work on. */
function setProfileContext(baseControls, baseReference, profile, effective) {
    BASE_CONTROLS = baseControls;
    BASE_REFERENCE = baseReference;
    PROFILE = profile || null;
    controls = effective || controls;
}
export { GR_PALETTE, grLayout, CY, CY_EXAMPLES, setProfileContext, validateProfile, overlayControls, overlayReference, profileStats, partyName, parseCSV, toCSV, workbookRows, profileFromWorkbook, tailoringRows, soaRows, rasciValid, WORKBOOK_COLUMNS, DEFAULT_PARTY_NAMES, PROFILE_VERSION };
`;
fs.mkdirSync(path.join(__dirname, '../src/generated'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '../src/generated/engine.js'), out);
console.log(`Extracted engine (${(out.length / 1024).toFixed(0)} KB) to src/generated/engine.js`);
